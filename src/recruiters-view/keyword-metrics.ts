export function keywordTextWidth(text: string, size: number) {
  return [...text].reduce((width, character) => {
    const code = character.codePointAt(0)!;
    return width + (geistMedium[code - 32] ?? (code >= 0x2e80 ? 1 : .65)) * size;
  }, 0);
}
